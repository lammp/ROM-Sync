def inno_script(version: str, dist: Path) -> str:
    """The Inno Setup script installing the frozen build in `dist` (F13-S3).

    The application goes to its own folder and the data to another: the person
    chooses the data folder, and one inside the application's (or around it) is
    refused. Every file the installer writes or deletes is under `{app}`, so
    replacing the application cannot touch the data. The uninstaller removes
    the application, leaves the data and its recorded folder, and says where
    the data is (F13-S4).
    """
    keys = "\n".join(
        f"  Result := Result or HasRuntime({hive}, '{key}');" for hive, key in WEBVIEW2_KEYS
    )
    return INNO.substitute(
        app=APP,
        app_id=APP_ID,
        version=version,
        install_dir=INSTALL_DIR,
        data_dir=DATA_DIR,
        data_key=DATA_KEY,
        source=dist / APP,
        min_version=f"10.0.{MIN_WINDOWS_BUILD}",
        webview2_keys=keys,
        bootstrapper=WEBVIEW2_BOOTSTRAPPER,
    )


#: What the interface's build may hold: web assets and nothing else (F13-S5).
INTERFACE_TYPES: Final = frozenset(
    {".html", ".css", ".js", ".json", ".txt", ".svg", ".ico", ".woff", ".woff2", ".map"}
)
#: What no artefact may hold, whatever else it carries: keys, firmware, game
#: images and archives, and a person's database.
CONTENT: Final = frozenset(
    {
        # keys and firmware
        ".keys", ".nca", ".nso",
        # game images and their containers
        ".nsp", ".xci", ".iso", ".cue", ".chd", ".cso", ".rvz", ".wbfs", ".pbp",
        ".3ds", ".cia", ".nds", ".gba", ".gbc", ".gb", ".sfc", ".smc", ".nes",
        ".n64", ".z64", ".v64", ".gen", ".sms", ".pce", ".7z", ".rar",
        # a library's state
        ".db", ".sqlite", ".sqlite3",
    }
)  # fmt: skip


class NotBuilt(RuntimeError):
    """The interface has not been built, so there is nothing to freeze with the engine."""


class HoldsContent(RuntimeError):
    """A folder headed for the artefact holds something that must never ship."""


def stray(folder: Path, allowed: frozenset[str] | None = None) -> list[Path]:
    """Files under `folder` that must not ship: content always, and anything
    outside `allowed` when it is given. Relative to `folder`, sorted by their
    POSIX spelling so the order is the same on every platform: Windows paths
    compare without case, so sorting the paths themselves differs by host."""
    found = []
    for path in folder.rglob("*"):
        suffix = path.suffix.casefold()
        if path.is_file() and (
            suffix in CONTENT or (allowed is not None and suffix not in allowed)
        ):
            found.append(path.relative_to(folder))
    return sorted(found, key=PurePath.as_posix)


def refuse_content(folder: Path, allowed: frozenset[str] | None = None) -> None:
    found = stray(folder, allowed)
    if found:
        listed = ", ".join(str(p) for p in found[:5])
        raise HoldsContent(f"{folder} holds {len(found)} file(s) that must not ship: {listed}")


def pyinstaller_args(
    bundle: Bundle, root: Path, dist: Path, work: Path, sep: str = os.pathsep
) -> list[str]:
    """PyInstaller's command line for `bundle`, every path absolute under `root`."""
    interface = root / bundle.data[0][0]
    if not (interface / MANIFEST).is_file():
        raise NotBuilt(f"build the interface first: {interface / MANIFEST} is missing")
    refuse_content(interface, INTERFACE_TYPES)
    args = [
        str(root / bundle.entry),
        "--name",
        bundle.name,
        "--onedir" if bundle.one_folder else "--onefile",
        "--windowed" if bundle.windowed else "--console",
        "--noconfirm",
        "--clean",
        "--distpath",
        str(dist),
        "--workpath",
        str(work),
        "--specpath",
        str(work),
    ]
    for path in bundle.paths:
        args += ["--paths", str(root / path)]
    for source, target in bundle.data:
        args += ["--add-data", f"{root / source}{sep}{target}"]
    for module in bundle.hidden:
        args += ["--hidden-import", module]
    for module in bundle.excluded:
        args += ["--exclude-module", module]
    return args


#: A version as a release may name it: digits, dots, and a plain suffix.
VERSION: Final = re.compile(r"^\d+\.\d+\.\d+([.-][0-9A-Za-z.]+)?\Z")


def release_version(tag: str) -> str:
    """The version a release tag names: `v0.1.0` is 0.1.0 (F13-S7). Anything
    else is refused: the version is written into the installer's script and its
    file name, so it may carry no quote, space or command (F16-S5)."""
    version = tag[1:] if tag[:1] in ("v", "V") else tag
    if not VERSION.match(version):
        raise ValueError(f"{tag!r} is not a release version such as v2.0.0")
    return version


def checksums(files: Sequence[Path]) -> str:
    """SHA-256 sums in the form `sha256sum --check` reads, one file per line by name."""
    lines = []
    for path in sorted(files, key=lambda p: p.name):
        digest = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(1024 * 1024), b""):
                digest.update(chunk)
        lines.append(f"{digest.hexdigest()}  {path.name}\n")
    return "".join(lines)


#: The release's checksum file, beside the artefacts it covers.
SUMS: Final = "SHA256SUMS.txt"


def package(out: Path, version: str) -> list[Path]:
    """The portable zip of the frozen application, and the checksums of every
    artefact in `out/artefacts` (the installer is compiled there first)."""
    app = out / "dist" / APP
    refuse_content(app)
    artefacts = out / "artefacts"
    artefacts.mkdir(parents=True, exist_ok=True)
    portable = artefacts / f"{APP}-{version}-portable.zip"
    with zipfile.ZipFile(portable, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(app.rglob("*")):
            if path.is_file():
                archive.write(path, Path(APP) / path.relative_to(app))
    shipped = sorted(p for p in artefacts.iterdir() if p.is_file() and p.name != SUMS)
    (artefacts / SUMS).write_text(checksums(shipped), encoding="utf-8")
    return [*shipped, artefacts / SUMS]


def iscc(which: Callable[[str], str | None] = shutil.which) -> Path | None:
    """Inno Setup's compiler: on the PATH, or where its installer puts it."""
    found = which("iscc") or which("ISCC")
    if found:
        return Path(found)
    for base in ("ProgramFiles(x86)", "ProgramFiles", "LOCALAPPDATA"):
        root = os.environ.get(base)
        if root:
            programs = Path(root) / ("Programs" if base == "LOCALAPPDATA" else "")
            candidate = programs / "Inno Setup 6" / "ISCC.exe"
            if candidate.is_file():
                return candidate
    return None


def main(argv: Sequence[str] | None = None) -> int:  # pragma: no cover - runs the build tools
    parser = argparse.ArgumentParser(prog="installer")
    parser.add_argument("command", choices=["build", "installer", "package"])
    parser.add_argument("--out", type=Path, default=ROOT / "reports" / "release")
    parser.add_argument("--version", default=_version(), help="a version, or a v-tag")
    args = parser.parse_args(argv)
    out: Path = args.out
    version = release_version(args.version)
    if args.command == "build":
        # PyInstaller is a build tool (the `build` extra), not something the engine imports
        freeze = importlib.import_module("PyInstaller.__main__").run
        freeze(pyinstaller_args(BUNDLE, ROOT, dist=out / "dist", work=out / "work"))
        return 0
    if args.command == "package":
        for made in package(out, version):
            print(made)
        return 0
    refuse_content(out / "dist" / APP)
    script = out / f"{APP}.iss"
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(inno_script(version, out / "dist"), encoding="utf-8")
    compiler = iscc()
    if compiler is None:
        print(f"wrote {script}; Inno Setup's ISCC was not found, so it was not compiled")
        return 1
    artefacts = out / "artefacts"
    return subprocess.run(
        [str(compiler), f"/O{artefacts}", str(script)], check=False
    ).returncode


def _version() -> str:  # pragma: no cover - read by the command line only
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    return next(
        line.split('"')[1] for line in text.splitlines() if line.startswith("version = ")
    )


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
